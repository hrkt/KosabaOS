# KosabaOS 最初のプログラム (riscv64)
# ===================================
# 起動直後、OpenSBI (ファームウェア) がこのコードを 0x80200000 に置いて
# S モードで渡してくる。その時点ではライブラリも printf も無いので、
# やることは 4 つだけ:
#   1. 作業場所 (スタック) を用意する
#   2. UART (シリアル通信のデバイス) を初期化する
#   3. 文字列を 1 文字ずつ、自前のドライバで UART へ出す
#   4. 終わったら眠って止まる
#
# 文字の出し方が今回変わった: 以前はファームウェアの SBI 呼び出し
# (ecall) に出力してもらっていたが、今はデバイスのレジスタを
# 自分で直接叩く。これが KosabaOS の最初のデバイスドライバ。
#
# 使うレジスタ (CPU の中にある超高速の小さな変数箱):
#   sp  : スタック (作業机) の場所
#   s1  : 文字列の「今読んでいる位置」を指す指 (読み取りヘッド)
#   a0  : uart_putc へ渡す 1 文字を入れる箱 (引数)
#   t0/t1: ドライバ内部の一時的な計算用 (呼び出し側は保存しない約束)
#   ra  : call で飛ぶときに「戻り先の住所」を入れる箱

    .section .text          # ここから先は「命令 (コード)」の領域
    .globl _start           # _start を外から見える入口として公開
_start:                     # カーネルの入口 (kernel.ld の ENTRY がここ)

# --- 1. スタックを用意する -------------------------------------------
# stack_top (下で確保した 4KB の末尾) のアドレスを sp に入れる。
# スタックは下向きに伸びるので、末尾を指すのが決まり。
# RISC-V はアドレスを 1 命令で運べないため、上半分 (auipc) と
# 下半分 (addi) の 2 命令で運ぶ。しかも「今いる場所 (PC) から数えた
# 相対位置」で計算するので、配置がずれても壊れない。
# (普通の la 命令は裏で GOT を経由し、こういう裸のバイナリでは動かない)
#
# ここで使う 2 命令の意味:
#   auipc (Add Upper Immediate to PC)
#     計算: rd = PC + (即値 << 12)
#     元になるのはレジスタではなく PC (今実行している命令のアドレス)。
#     即値は 20 ビットで、12 ビット左にずらして使うため、足し算は
#     4KB ページ単位の大ざっぱなものになる。「目的地のページまで行く」役。
#     %pcrel_hi(目標) は、PC から目標までの距離のうち、この上位部分。
#   addi (Add Immediate)
#     計算: rd = rs + 即値
#     元になるのは指定したレジスタ。即値は命令の中に直接書かれた
#     12 ビットの符号付き数 (-2048 〜 +2047) で、小さい調整専用。
#     「ページの中の細かい位置合わせ」役。%pcrel_lo(ラベル) は、
#     ペアになる auipc が運んだ上位部分の、残りの下位部分を指す。
#     あとで出てくる addi s1, s1, 1 (ポインタを 1 進める) も同じ命令。
#
# 実例 (このファイルのビルド結果の実数):
#   PC = 0x80200000、目標 stack_top = 0x80201050 のとき
#   auipc sp, 1      → sp = 0x80200000 + 0x1000 = 0x80201000
#   addi  sp, sp, 80 → sp = 0x80201000 + 0x50   = 0x80201050 で完成
.Lsp: auipc sp, %pcrel_hi(stack_top)
    addi sp, sp, %pcrel_lo(.Lsp)

# --- 2. UART を初期化する --------------------------------------------
    call uart_init          # 下のドライバ部品を呼ぶ (戻り先は ra に入る)

# --- 3. 文字列の先頭を指す --------------------------------------------
# スタックのときと同じやり方で、文字列 msg のアドレスを s1 に入れる。
.Lmsg: auipc s1, %pcrel_hi(msg)
    addi s1, s1, %pcrel_lo(.Lmsg)

# --- 4. 1 文字ずつ出すループ -------------------------------------------
# 数字ラベルは使い捨ての目印。2f = 前方 (forward) の 2、1b = 後方 (backward) の 1。
1:  lbu a0, 0(s1)           # s1 の指す場所から 1 文字読んで a0 へ
    beqz a0, 2f             # その文字が 0 (文字列の終わり) なら終了へ
    call uart_putc          # 自前のドライバで 1 文字出す
    addi s1, s1, 1          # 指を 1 文字進める
    j 1b                    # ループ先頭へ戻る

# --- 5. 眠って止まる ----------------------------------------------------
# 出すものは出し切ったし、まだシェルも何も無い。止めないと CPU が
# メモリの先を勝手に実行しに行って暴走するので、ここで「駐車」させる。
2:  wfi                     # 割り込みが来るまで CPU を眠らせる
    j 2b                    # 目覚めてもまた眠る (無限ループ)

# ======================================================================
# UART ドライバ (NS16550A) — KosabaOS の最初のデバイスドライバ
# ======================================================================
# デバイスはメモリと同じ住所空間に住んでいる (MMIO)。QEMU virt では
# UART の先頭アドレス (ベース) が 0x10000000 で、機能ごとの窓口
# (レジスタ) がそこからの距離 (オフセット) で並んでいる:
#   +0  THR  送信用 (書くと 1 文字送られる) ※受信 RBR と同じ住所
#   +1  IER  割り込みを有効にする設定
#   +2  FCR  FIFO (送受信の待ち行列) の設定 ※書く専用
#   +3  LCR  通信の形式設定。「分周比を書くモード」への切替ビットもここ
#   +5  LSR  状態表示。bit5 (0x20) = 送信窓口が空いた、bit0 = 受信あり
# RAM と違い、値を置くこと自体がデバイスへの命令になる。
# ベースアドレスはボードごとに違う (これは QEMU virt の値)。

# --- UART の初期化 ------------------------------------------------------
# 電源投入直後の UART は設定が定まっていないので、通信の約束を
# 書き込んでから使う。順番は 16550 系の定石どおり。
uart_init:
    li t0, 0x10000000       # t0 = UART のベースアドレス
    sb zero, 1(t0)          # IER = 0: 割り込みは使わない (今は自力で待つ)
    li t1, 0x80
    sb t1, 3(t0)            # LCR: 分周比を書くモードに切り替える
    li t1, 3
    sb t1, 0(t0)            # 分周比の下半分 = 3 (実機の標準クロックでは
    sb zero, 1(t0)          #   38400 bps になる値。上半分は 0)
    li t1, 0x03
    sb t1, 3(t0)            # LCR = 8 ビット・パリティなし・ストップ 1 (8N1)
                            # に戻すと分周比はロックされる
    li t1, 0x07
    sb t1, 2(t0)            # FCR: FIFO を有効にして中身を空にする
    ret                     # ra の示す場所へ戻る

# --- 1 文字送る ----------------------------------------------------------
# 入力: a0 = 送りたい 1 文字
uart_putc:
    li t0, 0x10000000       # t0 = UART のベースアドレス
1:  lbu t1, 5(t0)           # LSR (状態) を読む
    andi t1, t1, 0x20       # bit5「送信窓口が空」だけを取り出す
    beqz t1, 1b             # 空いていなければ読み直して待ち続ける
    sb a0, 0(t0)            # THR へ 1 文字置く = 送信される
    ret

# --- データ -------------------------------------------------------------
    .section .rodata        # 読み取り専用データの領域
msg:
    .string "hello from KosabaOS (S-mode)\n"
                            # .string は末尾に自動で 0 を付ける。
                            # 上のループはその 0 を「もう文字がない」の合図に使う。

    .section .bss           # 初期値ゼロの領域 (バイナリファイルに実体は入らない)
    .align 4
stack:
    .space 4096             # スタック用に 4KB 確保して
stack_top:                  # その末尾がスタックの出発点
